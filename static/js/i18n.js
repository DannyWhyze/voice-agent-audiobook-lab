let currentLanguage = getCookie(LANGUAGE_COOKIE) === "en" ? "en" : "de";

export function getLanguage() {
  return currentLanguage;
}

export function t(key, ...args) {
  const value = TRANSLATIONS[currentLanguage][key];
  if (typeof value === "function") {
    return value(...args);
  }
  return value !== undefined ? value : key;
}

export function applyTranslations() {
  document.documentElement.lang = currentLanguage;

  for (const el of document.querySelectorAll("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of document.querySelectorAll("[data-i18n-placeholder]")) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  }
  for (const el of document.querySelectorAll("[data-i18n-title]")) {
    el.title = t(el.dataset.i18nTitle);
  }
}

export function setLanguage(lang) {
  currentLanguage = lang === "en" ? "en" : "de";
  applyTranslations();
  fetch(`/language/${currentLanguage}`, { method: "POST" }).catch(() => {});
}

const languageToggleBtn = document.getElementById("language-toggle-btn");

function updateToggleLabel() {
  languageToggleBtn.textContent = currentLanguage === "de" ? "EN" : "DE";
}

languageToggleBtn.addEventListener("click", () => {
  setLanguage(currentLanguage === "de" ? "en" : "de");
  updateToggleLabel();
});

updateToggleLabel();
applyTranslations();
